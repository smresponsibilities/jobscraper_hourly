import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

// Server-only project composition and the legacy static answer bank require
// private state or unverified defaults. Leave those answers for manual review.
const browserOnly = {
  name: 'browser-safe-answer-sources',
  setup(build) {
    build.onResolve({ filter: /^\.\/(narrative-composer|portal-question-bank-1000)\.js$/ }, args => ({ path: args.path, namespace: 'browser-answer-stub' }));
    build.onLoad({ filter: /.*/, namespace: 'browser-answer-stub' }, args => ({
      contents: args.path.includes('narrative-composer')
        ? 'export const composeGroundedNarrative = () => null; export const composePortfolioProjectNarrative = () => null;'
        : 'export const lookupQuestionIn1000Bank = () => undefined;',
      loader: 'js',
    }));
  },
};

const bundled = await build({ entryPoints: ['src/autoapply/extension-answer-browser.ts'], bundle: true, platform: 'browser', format: 'iife', globalName: 'JobscraperAnswers', write: false, minify: true, plugins: [browserOnly] });
writeFileSync('extension/content/content.js', '// Generated by scripts/build-extension.mjs. Edit content.source.js or shared answers.\n' + bundled.outputFiles[0].text + '\n' + readFileSync('extension/content/content.source.js', 'utf8'));
